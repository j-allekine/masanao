import { expect, test } from "@playwright/test";
import Database from "better-sqlite3";

const mealPath = "/activity-designs/e2e-stock-design/activities/e2e-stock-activity/meal-schedules/e2e-stock-meal";
test.beforeAll(() => {
  const db = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
  db.exec(`INSERT INTO activity_design (id,activityDesignNo,fiscalYear,title,createdAt,updatedAt) VALUES ('e2e-stock-design','AD-STOCK',2026,'Stock training',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);
    INSERT INTO activity (id,activityDesignId,name,officeName,scheduledDate,plannedParticipantCount,createdAt,updatedAt) VALUES ('e2e-stock-activity','e2e-stock-design','Stock preparation','Kitchen',CURRENT_TIMESTAMP,NULL,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);
    INSERT INTO meal_schedule (id,activityId,label,mealTime,createdAt,updatedAt) VALUES ('e2e-stock-meal','e2e-stock-activity','Dinner','18:00',CURRENT_TIMESTAMP,CURRENT_TIMESTAMP);`);
  db.close();
});

test("staff adds exact alternate Stock quantity, reopens unchanged factors, edits and removes with mobile validation", async ({ page }, testInfo) => {
  test.setTimeout(120_000);
  expect((await page.request.post("/api/auth/sign-in/username", { data: { username: "kitchen.staff", password: "correct-horse-battery-staple" }, headers: { origin: process.env.BETTER_AUTH_URL! } })).status()).toBe(200);
  await page.goto(mealPath);
  await page.getByRole("link", { name: "Open issuance draft" }).click();
  await expect(page.locator('[data-issuance-ready="true"]')).toBeVisible({ timeout: 30_000 });
  await expect(page.getByLabel("Meal pax", { exact: true })).toHaveValue("");
  await page.getByRole("button", { name: "Add", exact: true }).click();
  await page.getByRole("menuitem", { name: "Stock item", exact: true }).click();
  const dialog = page.getByRole("dialog", { name: "Add Stock item" });
  await dialog.getByLabel("Search Items").fill("Rice");
  await dialog.getByRole("combobox", { name: "Item", exact: true }).click();
  await page.getByRole("option", { name: "Rice", exact: true }).click();
  await dialog.getByLabel("Quantity", { exact: true }).fill("1250.123456789123");
  await dialog.getByRole("combobox", { name: "Unit", exact: true }).click();
  await page.getByRole("option", { name: /Gram.*0\.001/ }).click();
  await page.screenshot({ path: testInfo.outputPath("desktop-stock-picker.png"), fullPage: true });
  await dialog.getByRole("button", { name: "Add Stock item", exact: true }).click();
  await expect(page.getByText(/1250\.123456789123 g/)).toBeVisible();
  await page.getByRole("button", { name: "Save draft" }).click();
  await expect(page.getByRole("status")).toContainText("Draft saved");
  const db = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
  db.prepare("UPDATE item_unit_conversion SET baseUnitQuantity = '0.002' WHERE id = 'e2e-recipe-conversion-rice-gram'").run();
  await page.reload();
  await expect(page.locator('[data-issuance-ready="true"]')).toBeVisible({ timeout: 30_000 });
  await expect(page.getByText(/1 g = 0\.001 kg/)).toBeVisible();
  await page.getByLabel("Meal pax", { exact: true }).fill("100");
  await page.getByRole("button", { name: "Save draft" }).click();
  await expect(page.getByRole("status")).toContainText("Draft saved");
  expect(db.prepare("SELECT conversionFactor FROM issuance_stock_item").get()).toEqual({ conversionFactor: "0.001" });
  await page.setViewportSize({ width: 320, height: 720 });
  await page.getByLabel("Actions for Stock item Rice").click();
  await page.getByRole("menuitem", { name: "Edit Stock item" }).click();
  await page.keyboard.press("Escape");
  await expect(page.getByLabel("Actions for Stock item Rice")).toBeFocused();
  await page.getByLabel("Actions for Stock item Rice").click();
  await page.getByRole("menuitem", { name: "Edit Stock item" }).click();
  const edit = page.getByRole("dialog", { name: "Edit Stock item" });
  await expect(edit.getByLabel("Quantity", { exact: true })).toHaveValue("1250.123456789123");
  await edit.getByLabel("Quantity", { exact: true }).fill("0");
  await edit.getByRole("button", { name: "Apply changes" }).click();
  await expect(edit.getByRole("alert")).toContainText("positive decimal quantity");
  await expect(edit.getByLabel("Quantity", { exact: true })).toHaveAttribute("aria-invalid", "true");
  await page.screenshot({ path: testInfo.outputPath("mobile-stock-validation.png"), fullPage: true });
  await edit.getByLabel("Quantity", { exact: true }).fill("1500.987654321123");
  await edit.getByRole("button", { name: "Apply changes" }).focus();
  await page.keyboard.press("Enter");
  await expect(page.getByText(/1 g = 0\.002 kg/)).toBeVisible();
  await expect.poll(() => page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.getByRole("button", { name: "Save draft" }).click();
  await expect(page.getByRole("status")).toContainText("Draft saved");
  await page.screenshot({ path: testInfo.outputPath("mobile-stock-saved.png"), fullPage: true });
  expect(db.prepare("SELECT enteredQuantity,conversionFactor FROM issuance_stock_item").get()).toEqual({ enteredQuantity: "1500.987654321123", conversionFactor: "0.002" });
  await page.getByLabel("Actions for Stock item Rice").click();
  await page.getByRole("menuitem", { name: "Remove Stock item" }).click();
  await page.getByRole("button", { name: "Save draft" }).click();
  await expect(page.getByRole("status")).toContainText("Draft saved");
  await page.reload();
  await expect(page.getByText("No Stock items selected. Add a Stock item for direct issuance.")).toBeVisible();
  expect(db.prepare("SELECT count(*) AS count FROM issuance_stock_item").get()).toEqual({ count: 0 });
  expect(db.prepare("SELECT count(*) AS count FROM inventory_ledger_movement WHERE movementType = 'stock-out'").get()).toEqual({ count: 0 });
  db.close();
});

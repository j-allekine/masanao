import Database from "better-sqlite3";
import type { Locator, Page } from "@playwright/test";
import { expect, test, selectOpeningItems } from "./fixture";
import { postFixtureSignIn } from "../e2e/fixture-auth";

const longName = "Batch rice with a longer descriptive package and storage label for the kitchen";
test.use({ actionTimeout: 15_000 });
test.beforeEach(() => {
  const db = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
  db.prepare('INSERT INTO unit (id,name,normalizedName,abbreviation,normalizedAbbreviation,active,createdAt,updatedAt) VALUES (?,?,?,?,?,1,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)').run('batch-sack','Batch Sack','batch sack','bs','bs');
  const insert = db.prepare('INSERT INTO item (id,name,normalizedName,categoryId,baseUnitId,reorderLevel,isActive,createdAt,updatedAt) VALUES (?,?,?,\'default-category-staples-dry-goods\',\'default-unit-kilogram\',\'0\',1,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)');
  insert.run('batch-rice',longName,longName.toLowerCase());
  insert.run('batch-salt','Batch salt','batch salt');
  db.close();
});

async function fields(page: Page, editor: Locator) {
  await editor.getByRole("combobox", { name: "Category", exact: true }).click();
  await page.getByRole("option", { name: "Staples & Dry Goods", exact: true }).click();
  await editor.getByRole("combobox", { name: "Base Unit", exact: true }).click();
  await page.getByRole("option", { name: "Kilogram (kg)", exact: true }).click();
  await editor.getByLabel("Reorder level", { exact: false }).fill("1");
  await editor.getByRole("button", { name: "Add alternate Unit", exact: true }).click();
  await editor.getByRole("combobox", { name: "Alternate Unit 1", exact: true }).click();
  await page.getByRole("option", { name: "Batch Sack (bs)", exact: true }).click();
  await editor.getByRole("textbox", { name: "Base Unit quantity 1", exact: true }).fill("25");
}

for (const width of [1440, 320]) {
  test(`catalog units and pending batch selection stay consistent at ${width}px`, async ({ page }, info) => {
    test.setTimeout(180_000);
    await page.setViewportSize({ width, height: 800 });
    expect((await postFixtureSignIn(page.request, { data: { username: "municipal.admin", password: "administrator-password" }, headers: { origin: process.env.BETTER_AUTH_URL! } })).status()).toBe(200);
    await page.goto("/items");
    await expect(page.locator('[data-items-ready="true"]')).toBeVisible();
    await page.getByRole("button", { name: "Create Item", exact: true }).click();
    let editor = page.getByRole("dialog", { name: "Create Item", exact: true });
    const catalogName = `Batch catalog flour ${width}`;
    await editor.getByLabel("Name", { exact: false }).fill(catalogName);
    await fields(page, editor);
    const baseUnit = editor.getByRole("combobox", { name: "Base Unit", exact: true });
    await baseUnit.scrollIntoViewIfNeeded();
    await baseUnit.press("Space");
    await expect(baseUnit).toHaveAttribute("aria-expanded", "true");
    await page.getByRole("option", { name: "Can (can)", exact: true }).click();
    await expect(editor.getByRole("textbox", { name: "Base Unit quantity 1", exact: true })).toHaveValue("");
    await baseUnit.press("Space");
    await expect(baseUnit).toHaveAttribute("aria-expanded", "true");
    await page.getByRole("option", { name: "Kilogram (kg)", exact: true }).click();
    await editor.getByLabel("Reorder level", { exact: false }).fill("1");
    await editor.getByRole("textbox", { name: "Base Unit quantity 1", exact: true }).fill("oops");
    await editor.getByRole("button", { name: "Create Item", exact: true }).click();
    await expect(editor.getByRole("textbox", { name: "Base Unit quantity 1", exact: true })).toBeFocused();
    let db = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
    expect(db.prepare('SELECT id FROM item WHERE name=?').get(catalogName)).toBeUndefined();
    db.close();
    await editor.getByRole("textbox", { name: "Base Unit quantity 1", exact: true }).fill("25");
    await page.screenshot({ path: info.outputPath(`catalog-units-${width}.png`) });
    await editor.getByRole("button", { name: "Create Item", exact: true }).click();
    await expect(editor).toBeHidden();

    await page.goto("/inventory/opening-stock");
    await page.getByRole("button", { name: "Start opening stock", exact: true }).click();
    await page.getByRole("button", { name: "Add items", exact: true }).click();
    await selectOpeningItems(page, [catalogName]);
    await page.getByRole("textbox", { name: `Quantity for ${catalogName}`, exact: true }).filter({ visible: true }).fill("2");
    await page.getByRole("textbox", { name: `Opening unit cost for ${catalogName}`, exact: true }).filter({ visible: true }).fill("10");
    await page.getByRole("button", { name: "Add items", exact: true }).click();
    let picker = page.getByRole("dialog", { name: "Add items", exact: true });
    await expect(picker.getByRole("checkbox", { name: `Select ${catalogName}`, exact: true })).toBeDisabled();
    await expect(picker.getByRole("checkbox", { name: `Select ${catalogName}`, exact: true })).toBeChecked();
    await expect(picker.getByRole("button", { name: "Add selected (0)", exact: true })).toBeDisabled();
    await picker.getByRole("checkbox", { name: `Select ${longName}`, exact: true }).check();
    await picker.getByLabel("Search Items", { exact: true }).fill("Batch salt");
    await picker.getByRole("checkbox", { name: "Select Batch salt", exact: true }).check();
    await expect(picker.getByText("2 new Items selected", { exact: true })).toBeVisible();
    const createdName = `Batch new grain ${width}`;
    await picker.getByLabel("Search Items", { exact: true }).fill(createdName);
    await picker.getByRole("button", { name: "Create Item", exact: true }).click();
    editor = page.getByRole("dialog", { name: "Create Item", exact: true });
    await editor.getByLabel("Name", { exact: false }).fill("Discard this new item");
    await editor.getByRole("button", { name: "Back to items", exact: true }).click();
    await page.getByRole("alertdialog").getByRole("button", { name: "Discard Item changes", exact: true }).click();
    picker = page.getByRole("dialog", { name: "Add items", exact: true });
    await expect(picker.getByLabel("Search Items", { exact: true })).toHaveValue(createdName);
    await expect(picker.getByText("2 new Items selected", { exact: true })).toBeVisible();
    await picker.getByRole("button", { name: "Create Item", exact: true }).click();
    editor = page.getByRole("dialog", { name: "Create Item", exact: true });
    await fields(page, editor);
    await editor.getByRole("button", { name: "Create Item", exact: true }).click();
    picker = page.getByRole("dialog", { name: "Add items", exact: true });
    await expect(picker.getByText("3 new Items selected", { exact: true })).toBeVisible();
    await expect(picker.getByRole("checkbox", { name: `Select ${createdName}`, exact: true })).toBeChecked();
    await expect(page.getByRole("dialog")).toHaveCount(1);
    await picker.getByLabel("Search Items", { exact: true }).fill("Batch");
    await expect(picker.getByRole("button", { name: "Add selected (3)", exact: true })).toBeInViewport();
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    await page.screenshot({ path: info.outputPath(`batch-selection-${width}.png`) });
    await picker.getByRole("button", { name: "Cancel", exact: true }).click();
    await expect(picker).toBeHidden();
    await expect(page.getByRole("textbox", { name: `Quantity for ${createdName}`, exact: true })).toHaveCount(0);
    await expect(page.getByRole("textbox", { name: `Quantity for ${catalogName}`, exact: true }).filter({ visible: true })).toHaveValue("2");
    await page.getByRole("button", { name: "Add items", exact: true }).click();
    await selectOpeningItems(page, [longName, "Batch salt", createdName]);
    await expect(page.getByRole("textbox", { name: `Quantity for ${createdName}`, exact: true }).filter({ visible: true })).toHaveValue("");
    await expect(page.getByRole("textbox", { name: `Opening unit cost for ${createdName}`, exact: true }).filter({ visible: true })).toHaveValue("");
    await page.getByRole("button", { name: "Save draft", exact: true }).click();
    await expect(page.getByRole("status")).toContainText("draft saved");
    await expect(page.getByRole("button", { name: "Save draft", exact: true })).toBeEnabled();
    await page.reload();
    await expect(page.locator('[data-opening-stock-ready="true"]')).toBeVisible();
    await expect(page.getByRole("textbox", { name: `Quantity for ${catalogName}`, exact: true }).filter({ visible: true })).toHaveValue("2");
    db = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
    expect(db.prepare('SELECT COUNT(*) AS n FROM item_unit_conversion c JOIN item i ON c.itemId=i.id WHERE i.name IN (?,?)').get(catalogName, createdName)).toMatchObject({ n: 2 });
    expect(db.prepare('SELECT COUNT(*) AS n FROM opening_stock_line').get()).toMatchObject({ n: 4 });
    expect(db.prepare('SELECT COUNT(*) AS n FROM inventory_ledger_movement').get()).toMatchObject({ n: 0 });
    db.close();
  });
}

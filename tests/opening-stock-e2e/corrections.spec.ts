import Database from "better-sqlite3";
import { expect, test, selectOpeningItems } from "./fixture";
import { postFixtureSignIn } from "../e2e/fixture-auth";

const existing = "Correction Rice";
const created = "Correction supplied salt with a deliberately long descriptive Item name";

test.beforeEach(() => {
  const database = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
  database.exec(`INSERT INTO item (id,name,normalizedName,categoryId,baseUnitId,reorderLevel,isActive,createdAt,updatedAt)
    VALUES ('correction-ui-rice','${existing}','correction rice','default-category-staples-dry-goods','default-unit-kilogram','1',1,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)`);
  database.close();
});

test("omitted stock persists, reviews explicit costs and posts linked desktop/mobile history", async ({ page, browser }, info) => {
  test.setTimeout(240_000);
  expect((await postFixtureSignIn(page.request, { data: { username: "municipal.admin", password: "administrator-password" }, headers: { origin: process.env.BETTER_AUTH_URL! } })).status()).toBe(200);
  await page.setViewportSize({ width: 1440, height: 1000 });
  await page.goto("/inventory/opening-stock");
  await expect(page.locator('[data-opening-stock-ready="true"]')).toBeVisible();
  await page.getByRole("button", { name: "Start opening stock", exact: true }).click();
  await page.getByRole("button", { name: "Add items", exact: true }).click();
  await page.getByLabel("Search Items", { exact: true }).fill(existing);
  await selectOpeningItems(page, [existing]);
  await page.getByRole("textbox", { name: `Quantity for ${existing}`, exact: true }).fill("2");
  await page.getByRole("textbox", { name: `Opening unit cost for ${existing}`, exact: true }).fill("3");
  await page.getByRole("button", { name: "Review opening stock", exact: true }).click();
  await page.getByRole("button", { name: "Post opening stock", exact: true }).click();
  await expect(page.getByRole("heading", { name: "OS-0001", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Record correction", exact: true }).click();
  await page.getByRole("button", { name: "Add omitted stock", exact: true }).click();
  let editor = page.getByRole("dialog", { name: "Add omitted stock", exact: true });
  await expect(editor).toBeVisible();
  await editor.getByRole("button", { name: "Add items", exact: true }).click();
  const picker = page.getByRole("dialog", { name: "Add omitted Item", exact: true });
  await picker.getByRole("textbox", { name: "Search Items", exact: true }).fill(existing);
  await picker.getByRole("button", { name: new RegExp(`^${existing} `) }).click();
  await editor.getByRole("textbox", { name: "Added quantity", exact: true }).fill("0.5");
  await editor.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(editor.getByRole("status")).toContainText("draft saved");
  await editor.getByRole("button", { name: "Close", exact: true }).click();
  await page.reload();
  await page.getByRole("button", { name: "Resume draft", exact: true }).click();
  editor = page.getByRole("dialog", { name: "Add omitted stock", exact: true });
  await expect(editor.getByRole("textbox", { name: "Added quantity", exact: true })).toHaveValue("0.5");
  await expect(editor.getByRole("textbox", { name: "Opening unit cost", exact: true })).toHaveValue("");
  await editor.getByRole("button", { name: "Review correction", exact: true }).click();
  let review = page.getByRole("dialog", { name: "Review correction", exact: true });
  await expect(review.getByRole("button", { name: "Post correction", exact: true })).toBeDisabled();
  await expect(review).toContainText("Unknown");
  await review.getByRole("button", { name: "Back to correction", exact: true }).click();
  await editor.getByRole("textbox", { name: "Reason for correction", exact: true }).fill("Count sheet omitted a half-kilogram package and supplies already on hand.");
  await editor.getByRole("textbox", { name: "Supporting notes (optional)", exact: true }).fill("Supporting count sheet. The posting timestamp is assigned by the server.");
  await editor.getByRole("textbox", { name: "Opening unit cost", exact: true }).fill("4");
  await editor.getByRole("button", { name: "Add items", exact: true }).click();
  await picker.getByRole("textbox", { name: "Search Items", exact: true }).fill(created);
  await picker.getByRole("button", { name: `Create Item: ${created}`, exact: true }).click();
  const itemEditor = page.getByRole("dialog", { name: "Create Item", exact: true });
  await itemEditor.getByRole("combobox", { name: "Category", exact: true }).click();
  await page.getByRole("option", { name: "Staples & Dry Goods", exact: true }).click();
  await itemEditor.getByRole("combobox", { name: "Base Unit", exact: true }).click();
  await page.getByRole("option", { name: "Kilogram (kg)", exact: true }).click();
  await itemEditor.getByLabel("Reorder level", { exact: false }).fill("1");
  await itemEditor.getByRole("button", { name: "Add alternate Unit", exact: true }).click();
  await itemEditor.getByRole("combobox", { name: "Alternate Unit 1", exact: true }).click();
  await page.getByRole("option", { name: "Gram (g)", exact: true }).click();
  await itemEditor.getByRole("textbox", { name: "Base Unit quantity 1", exact: true }).fill("0.001");
  await itemEditor.getByRole("button", { name: "Create Item", exact: true }).click();
  await expect(itemEditor).toBeHidden();
  const addedCard = editor.locator('[data-slot="card"]').filter({ has: page.getByText(created, { exact: true }) });
  await addedCard.getByRole("textbox", { name: "Added quantity", exact: true }).fill("250");
  await addedCard.getByRole("combobox", { name: "Unit", exact: true }).click();
  await page.getByRole("option", { name: "Gram (0.001 kg)", exact: true }).click();
  await addedCard.getByRole("textbox", { name: "Opening unit cost", exact: true }).fill("0");
  await addedCard.getByRole("textbox", { name: "Reason for zero cost", exact: true }).fill("Explicitly confirmed zero opening value.");
  await expect(editor.getByRole("textbox", { name: "Reason for correction", exact: true })).toHaveValue("Count sheet omitted a half-kilogram package and supplies already on hand.");
  await editor.getByRole("button", { name: "Review correction", exact: true }).click();
  review = page.getByRole("dialog", { name: "Review correction", exact: true });
  await expect(review).toContainText("0.25 kg");
  await expect(review).toContainText("Net stock effect");
  await expect(review.getByRole("button", { name: "Post correction", exact: true })).toBeDisabled();
  await page.screenshot({ path: info.outputPath("omitted-correction-review-desktop.png"), fullPage: true });
  await page.setViewportSize({ width: 320, height: 800 });
  await review.getByRole("checkbox").check();
  await expect(review.getByRole("button", { name: "Post correction", exact: true })).toBeEnabled();
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("omitted-correction-review-mobile.png"), fullPage: true });
  await review.getByRole("button", { name: "Post correction", exact: true }).click();
  const detail = page.getByRole("dialog");
  await expect(detail.getByText("Posted correction. The original count and prior issuance evidence are preserved.", { exact: false })).toBeVisible();
  await expect(detail.getByRole("button", { name: "Save draft", exact: true })).toHaveCount(0);
  await expect(detail.getByRole("button", { name: "Discard draft", exact: true })).toHaveCount(0);
  await expect(detail).toContainText("Municipal Administrator");
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath("omitted-correction-detail-mobile.png"), fullPage: true });
  await detail.getByRole("button", { name: "Close", exact: true }).last().click();
  await expect(page.getByRole("heading", { name: "Original counted quantities", exact: true })).toBeVisible();
  await expect(page.getByRole("heading", { name: "Current opening-derived stock", exact: true })).toBeVisible();
  await page.getByRole("button", { name: "Record correction", exact: true }).click();
  await page.getByRole("button", { name: "Add omitted stock", exact: true }).click();
  editor = page.getByRole("dialog", { name: "Add omitted stock", exact: true });
  await editor.getByRole("textbox", { name: "Reason for correction", exact: true }).fill("Private administrator draft");
  await editor.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(editor.getByRole("status")).toContainText("draft saved");
  await editor.getByRole("button", { name: "Close", exact: true }).click();

  const staffContext = await browser.newContext({ baseURL: process.env.BETTER_AUTH_URL, viewport: { width: 1440, height: 1000 } });
  expect((await postFixtureSignIn(staffContext.request, { data: { username: "kitchen.staff", password: "correct-horse-battery-staple" }, headers: { origin: process.env.BETTER_AUTH_URL! } })).status()).toBe(200);
  const staff = await staffContext.newPage();
  await staff.goto("/inventory/opening-stock");
  await expect(staff.getByRole("button", { name: "View correction", exact: true })).toHaveCount(1);
  await expect(staff.getByRole("button", { name: "Resume draft", exact: true })).toHaveCount(0);
  await expect(staff.getByRole("button", { name: "Record correction", exact: true })).toHaveCount(0);
  await expect(staff.getByText("Private administrator draft", { exact: true })).toHaveCount(0);
  await staff.getByRole("button", { name: "View correction", exact: true }).click();
  await expect(staff.getByRole("dialog")).toContainText("Count sheet omitted a half-kilogram package");
  await staff.screenshot({ path: info.outputPath("omitted-correction-staff-desktop.png"), fullPage: true });
  await staffContext.close();
  await page.getByRole("button", { name: "Resume draft", exact: true }).click();
  await editor.getByRole("button", { name: "Discard draft", exact: true }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Keep draft", exact: true }).click();
  await expect(editor).toBeVisible();
  await editor.getByRole("button", { name: "Discard draft", exact: true }).click();
  await page.getByRole("alertdialog").getByRole("button", { name: "Discard correction draft", exact: true }).click();
  await expect(page.getByRole("button", { name: "Resume draft", exact: true })).toHaveCount(0);
  const database = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
  expect(database.prepare("SELECT id FROM item WHERE name = ?").get(created)).toBeTruthy();
  expect(database.prepare("SELECT quantity FROM opening_stock_source WHERE itemId = ? ORDER BY position").all("correction-ui-rice")).toEqual([{ quantity: "2" }, { quantity: "0.5" }]);
  database.close();
});

import Database from "better-sqlite3";
import { mkdirSync } from "node:fs";
import { join } from "node:path";
import { expect, test, selectOpeningItems } from "./fixture";
import { postFixtureSignIn } from "../e2e/fixture-auth";

const itemName = "Opening replacement supply with a deliberately long descriptive label";
test.beforeEach(() => {
  const db = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
  db.prepare(`INSERT INTO item (id,name,normalizedName,categoryId,baseUnitId,reorderLevel,isActive,createdAt,updatedAt)
    VALUES (?,?,?,'default-category-staples-dry-goods','default-unit-piece','1',1,CURRENT_TIMESTAMP,CURRENT_TIMESTAMP)`).run("cost-correction-item", itemName, itemName.toLowerCase());
  db.close();
});

test("administrator replaces entire selected remainders with explicit costs and staff sees immutable evidence at 320px", async ({ page, browser }, testInfo) => {
  test.setTimeout(240_000);
  await page.setViewportSize({ width: 1440, height: 960 });
  expect((await postFixtureSignIn(page.request, { data: { username: "municipal.admin", password: "administrator-password" }, headers: { origin: process.env.BETTER_AUTH_URL! } })).status()).toBe(200);
  await page.goto("/inventory/opening-stock");
  await page.getByRole("button", { name: "Start opening stock", exact: true }).click();
  await page.getByRole("button", { name: "Add items", exact: true }).click();
  await selectOpeningItems(page, [itemName]);
  await page.getByLabel(`Quantity for ${itemName}`, { exact: true }).filter({ visible: true }).fill("3");
  await page.getByLabel(`Opening unit cost for ${itemName}`, { exact: true }).filter({ visible: true }).fill("0.01");
  await page.getByRole("button", { name: `Add another cost line for ${itemName}`, exact: true }).click();
  await page.getByLabel(`Quantity for ${itemName}, line 2`, { exact: true }).filter({ visible: true }).fill("2");
  await page.getByLabel(`Opening unit cost for ${itemName}, line 2`, { exact: true }).filter({ visible: true }).fill("2");
  await page.getByRole("button", { name: "Review opening stock", exact: true }).click();
  await page.getByRole("button", { name: "Post opening stock", exact: true }).click();
  await page.getByRole("button", { name: "Record correction", exact: true }).click();
  await page.getByRole("button", { name: "Correct remaining cost", exact: true }).click();
  let editor = page.getByRole("dialog", { name: "Correct remaining cost", exact: true });
  await editor.getByLabel("Reason for correction").fill("Correct the assigned costs of these remaining supplies using supported amounts.");
  await editor.getByRole("button", { name: "Select source lines", exact: true }).click();
  let picker = page.getByRole("dialog", { name: "Select source line", exact: true });
  await expect(picker.getByRole("button", { name: /source 1/ })).toContainText("Remaining: 3 pc");
  await expect(picker.getByRole("button", { name: /source 2/ })).toContainText("Residual value: ₱4");
  await picker.getByRole("button", { name: /source 1/ }).click();
  await expect(editor.getByLabel("Replacement cost per Base Unit (pc)")).toHaveValue("");
  await expect(editor.getByLabel(/quantity/i)).toHaveCount(0);
  await editor.getByRole("button", { name: "Save draft", exact: true }).click();
  await expect(editor.getByRole("status")).toContainText("No stock moved or was reserved");
  await page.reload();
  await page.getByRole("button", { name: "Resume draft", exact: true }).click();
  editor = page.getByRole("dialog", { name: "Correct remaining cost", exact: true });
  await expect(editor.getByLabel("Replacement cost per Base Unit (pc)")).toHaveValue("");
  await editor.getByRole("button", { name: "Review correction", exact: true }).click();
  let review = page.getByRole("dialog", { name: "Review correction", exact: true });
  await expect(review.getByRole("button", { name: "Post correction", exact: true })).toBeDisabled();
  await review.getByRole("button", { name: "Back to correction", exact: true }).click();
  await editor.getByLabel("Replacement cost per Base Unit (pc)").fill("0.02");
  await editor.getByRole("button", { name: "Select source lines", exact: true }).click();
  picker = page.getByRole("dialog", { name: "Select source line", exact: true });
  await page.keyboard.press("Escape");
  await expect(editor.getByRole("button", { name: "Select source lines", exact: true })).toBeFocused();
  await editor.getByRole("button", { name: "Select source lines", exact: true }).click();
  await picker.getByRole("button", { name: /source 2/ }).click();
  await editor.getByLabel("Replacement cost per Base Unit (pc)").nth(1).fill("0");
  await editor.getByLabel("Reason for zero cost").fill("Deliberately assigned zero based on the approved source evidence.");
  await editor.getByRole("button", { name: "Review correction", exact: true }).click();
  review = page.getByRole("dialog", { name: "Review correction", exact: true });
  await expect(review).toContainText("Previous source basis: ₱0.03 / 3 pc");
  await expect(review).toContainText("Old remaining value: ₱0.03");
  await expect(review).toContainText("Replacement value: ₱0.06");
  await expect(review).toContainText("Value difference: ₱0.03");
  await expect(review).toContainText("Value difference: -₱4");
  await expect(review).toContainText("Quantity before and after: 3 pc → 3 pc");
  await expect(review).toContainText("historical revaluation is unavailable");
  await expect(review.getByRole("button", { name: "Post correction", exact: true })).toBeDisabled();
  await review.getByRole("checkbox", { name: "I confirm the zero costs and their recorded reasons." }).check();
  const evidenceDir = process.env.MASANAO_OPENING_COST_EVIDENCE_DIR;
  if (evidenceDir) mkdirSync(evidenceDir, { recursive: true });
  for (const width of [1440, 320]) {
    await page.setViewportSize({ width, height: 900 });
    expect(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth)).toBe(true);
    expect(await review.evaluate((element) => element.scrollWidth <= element.clientWidth)).toBe(true);
    await expect(review.getByRole("button", { name: "Post correction", exact: true })).toBeInViewport();
    await page.screenshot({ path: evidenceDir ? join(evidenceDir, `cost-review-${width}.png`) : testInfo.outputPath(`cost-review-${width}.png`), fullPage: true });
  }
  await review.getByRole("button", { name: "Post correction", exact: true }).click();
  const posted = page.getByRole("dialog", { name: /OS-0001-C/ });
  await expect(posted).toContainText("Replacement value: ₱0.06");
  await expect(posted.getByRole("button", { name: "Post correction", exact: true })).toHaveCount(0);
  await page.screenshot({ path: evidenceDir ? join(evidenceDir, "cost-posted-320.png") : testInfo.outputPath("cost-posted-320.png"), fullPage: true });
  await posted.getByRole("button", { name: "Close", exact: true }).last().click();
  const db = new Database(process.env.MASANAO_E2E_DATABASE_PATH!);
  expect(db.prepare('SELECT quantity,amount FROM opening_stock_source WHERE itemId = ? AND originalSourceId IS NULL ORDER BY position').all("cost-correction-item")).toEqual([{ quantity: "3", amount: "0.03" }, { quantity: "2", amount: "4" }]);
  expect(db.prepare('SELECT quantity,amount FROM opening_stock_source WHERE itemId = ? AND originalSourceId IS NOT NULL ORDER BY position').all("cost-correction-item")).toEqual([{ quantity: "3", amount: "0.06" }, { quantity: "2", amount: "0" }]);
  expect(db.prepare('SELECT COUNT(*) AS count FROM opening_stock_withdrawal WHERE kind = ?').get("correction-retirement")).toEqual({ count: 2 });
  db.close();
  // A new administrator draft remains invisible to staff.
  await page.getByRole("button", { name: "Record correction", exact: true }).click();
  await page.getByRole("button", { name: "Correct remaining cost", exact: true }).click();
  await page.getByRole("dialog", { name: "Correct remaining cost", exact: true }).getByRole("button", { name: "Close", exact: true }).click();
  const staff = await browser.newContext({ baseURL: process.env.BETTER_AUTH_URL, viewport: { width: 320, height: 900 } });
  expect((await postFixtureSignIn(staff.request, { data: { username: "kitchen.staff", password: "correct-horse-battery-staple" }, headers: { origin: process.env.BETTER_AUTH_URL! } })).status()).toBe(200);
  const staffPage = await staff.newPage();
  await staffPage.goto("/inventory/opening-stock");
  await expect(staffPage.getByRole("button", { name: "Record correction", exact: true })).toHaveCount(0);
  await expect(staffPage.getByRole("button", { name: "Resume draft", exact: true })).toHaveCount(0);
  await expect(staffPage.getByText("Correct remaining cost · 2 lines", { exact: true })).toBeVisible();
  await staffPage.getByRole("button", { name: "View correction", exact: true }).click();
  await expect(staffPage.getByRole("dialog")).toContainText("Quantity before and after: 3 pc → 3 pc");
  await expect(staffPage.getByRole("dialog").getByRole("textbox")).toHaveCount(0);
  await staff.close();
});
